#!/usr/bin/env node
/* Purview Gurukul — lock and unlock a client playbook.
   The repository is public, so client playbooks are committed only as
   ciphertext. The page derives the key from the team passcode (PBKDF2,
   SHA-256, 600,000 rounds) and decrypts with AES-256-GCM in the browser.

   Lock:   SOP_PASSCODE='...' node tools/sop-lock.js lock sops-abw.js sops-abw.enc.js
   Unlock: SOP_PASSCODE='...' node tools/sop-lock.js unlock sops-abw.enc.js sops-abw.json
   The source file is plain JavaScript defining SOP_CLIENTS and SOP_QUIZ;
   it must never be committed (see .gitignore). */
"use strict";
const fs=require("fs"), vm=require("vm"), crypto=require("crypto");
const [cmd,inFile,outFile]=process.argv.slice(2);
const pass=(process.env.SOP_PASSCODE||"").normalize("NFKC").trim();
if(!cmd||!inFile||!outFile||!pass){ console.error("usage: SOP_PASSCODE=... node tools/sop-lock.js lock|unlock <in> <out>"); process.exit(2); }
const ITER=600000;
function key(salt){ return crypto.pbkdf2Sync(Buffer.from(pass,"utf8"),salt,ITER,32,"sha256"); }
if(cmd==="lock"){
  const ctx={}; vm.createContext(ctx);
  vm.runInContext(fs.readFileSync(inFile,"utf8")+";this.clients=typeof SOP_CLIENTS!=='undefined'?SOP_CLIENTS:[];this.quiz=typeof SOP_QUIZ!=='undefined'?SOP_QUIZ:[];",ctx);
  const plain=Buffer.from(JSON.stringify({clients:ctx.clients,quiz:ctx.quiz}),"utf8");
  const salt=crypto.randomBytes(16), iv=crypto.randomBytes(12);
  const c=crypto.createCipheriv("aes-256-gcm",key(salt),iv);
  const ct=Buffer.concat([c.update(plain),c.final(),c.getAuthTag()]);
  const out={v:1,kdf:"PBKDF2",hash:"SHA-256",iter:ITER,salt:salt.toString("base64"),alg:"AES-GCM",iv:iv.toString("base64"),ct:ct.toString("base64"),
    locked:new Date().toISOString().slice(0,10),clients:ctx.clients.map(x=>x.short||x.name).length};
  fs.writeFileSync(outFile,"/* Encrypted client playbook. Opens in the Purview SOPs tab with the team passcode. Generated by tools/sop-lock.js. */\nconst SOP_ENC="+JSON.stringify(out)+";\n");
  console.log("locked",inFile,"->",outFile,"plain bytes",plain.length,"clients",ctx.clients.length,"quiz",ctx.quiz.length);
} else if(cmd==="unlock"){
  const src=fs.readFileSync(inFile,"utf8"); const enc=JSON.parse(src.slice(src.indexOf("{"),src.lastIndexOf("}")+1));
  const buf=Buffer.from(enc.ct,"base64"), tag=buf.subarray(buf.length-16), body=buf.subarray(0,buf.length-16);
  const d=crypto.createDecipheriv("aes-256-gcm",crypto.pbkdf2Sync(Buffer.from(pass,"utf8"),Buffer.from(enc.salt,"base64"),enc.iter,32,"sha256"),Buffer.from(enc.iv,"base64"));
  d.setAuthTag(tag);
  const plain=Buffer.concat([d.update(body),d.final()]).toString("utf8");
  fs.writeFileSync(outFile,plain); const data=JSON.parse(plain);
  console.log("unlocked",inFile,"->",outFile,"clients",data.clients.length,"quiz",data.quiz.length);
} else { console.error("unknown command "+cmd); process.exit(2); }
